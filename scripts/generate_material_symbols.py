"""Export the prototype's exact static Material Symbols glyphs for Compose.

Run with Python + fonttools. This is an asset-generation tool, not an app dependency.
Source license: design/prototype-v1/assets/LICENSE-Material-Symbols.txt (Apache-2.0).
"""

from pathlib import Path
from shutil import copyfile
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design/prototype-v1/assets/symbols.ttf"
TARGET = ROOT / "composeApp/src/commonMain/kotlin/com/keno/rxplayer/ui/PlayerSymbols.kt"
LICENSE = ROOT / "composeApp/src/commonMain/composeResources/files/material_symbols_LICENSE.txt"
GLYPHS = {
    "PlayArrow": 0xE037,
    "Pause": 0xE034,
    "SkipPrevious": 0xE045,
    "SkipNext": 0xE044,
    "Shuffle": 0xE043,
    "Repeat": 0xE040,
    "QueueMusic": 0xE03D,
    "Favorite": 0xE87D,
    "ArrowBack": 0xE5C4,
    "Close": 0xE14C,
    "Refresh": 0xE5D5,
    "VolumeUp": 0xE050,
}

font = TTFont(SOURCE)
glyphs = font.getGlyphSet()
units = font["head"].unitsPerEm
cmap = font.getBestCmap()
text = '''// Generated by scripts/generate_material_symbols.py; do not edit paths by hand.
// Material Symbols Rounded SemiBold, Copyright Google LLC, Apache-2.0.
// Exact source and license: design/prototype-v1/assets/{symbols.ttf,LICENSE-Material-Symbols.txt}.
package com.keno.rxplayer.ui

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

/** Same glyph outlines as the confirmed prototype, independent of legacy Material Icons. */
internal object PlayerSymbols {
'''
for name, codepoint in GLYPHS.items():
    pen = SVGPathPen(glyphs)
    # Font coordinates point up; Compose points down. Preserve the full em square.
    glyphs[cmap[codepoint]].draw(TransformPen(pen, (1, 0, 0, -1, 0, units)))
    mirror = ", autoMirror = true" if name == "ArrowBack" else ""
    text += f'''    val {name}: ImageVector by lazy {{
        symbol("{name}", "{pen.getCommands()}"{mirror})
    }}
'''
text += f'''
    private fun symbol(name: String, data: String, autoMirror: Boolean = false): ImageVector =
        ImageVector.Builder(name = "PlayerSymbols.$name", defaultWidth = 24.dp, defaultHeight = 24.dp,
            viewportWidth = {units}f, viewportHeight = {units}f, autoMirror = autoMirror)
            .addPath(PathParser().parsePathString(data).toNodes(), fill = SolidColor(Color.Black))
            .build()
}}
'''
TARGET.write_text(text, encoding="utf-8", newline="\n")
copyfile(SOURCE.with_name("LICENSE-Material-Symbols.txt"), LICENSE)
print(f"Exported {len(GLYPHS)} prototype glyphs to {TARGET.relative_to(ROOT)}")
